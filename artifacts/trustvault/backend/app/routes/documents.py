
"""Private document upload and download endpoints."""

import os
from pathlib import Path
from uuid import UUID, uuid4

from fastapi import APIRouter, Depends, File, Form, HTTPException, UploadFile, status
from fastapi.responses import FileResponse
from sqlalchemy.orm import Session

from app.authorization import can_read, effective_document_role, record_audit
from app.database import get_db
from app.dependencies import get_current_user
from app.models import Document, User

router = APIRouter(prefix="/api/documents", tags=["documents"])

MAX_FILE_SIZE = 10 * 1024 * 1024  # 10 MiB
CHUNK_SIZE = 64 * 1024
STORAGE_DIR = Path(
    os.environ.get("TRUSTVAULT_STORAGE_DIR", "private_storage")
).resolve()


def _audit(
    db: Session,
    user: User,
    event_type: str,
    outcome: str,
    document_id: str,
    details: dict | None = None,
) -> None:
    record_audit(
        db,
        actor=user,
        event_type=event_type,
        outcome=outcome,
        resource_type="document",
        resource_id=document_id,
        details=details or {},
    )


@router.post("", status_code=status.HTTP_201_CREATED)
async def upload_document(
    file: UploadFile = File(...),
    category: str = Form(default="general", max_length=100),
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
) -> dict:
    """Store a private file and its database metadata."""
    original_name = (file.filename or "document").replace("\\", "/").split("/")[-1]
    original_name = original_name[:255].strip()

    if not original_name:
        raise HTTPException(status_code=400, detail="A filename is required")

    storage_key = uuid4().hex
    STORAGE_DIR.mkdir(parents=True, exist_ok=True)
    destination = STORAGE_DIR / storage_key
    size = 0

    try:
        with destination.open("xb") as output:
            while True:
                chunk = await file.read(CHUNK_SIZE)
                if not chunk:
                    break

                size += len(chunk)
                if size > MAX_FILE_SIZE:
                    raise HTTPException(
                        status_code=413,
                        detail="File exceeds the 10 MiB upload limit",
                    )
                output.write(chunk)

        document = Document(
            owner_id=user.id,
            name=original_name,
            category=category.strip() or "general",
            content_type=file.content_type or "application/octet-stream",
            size_bytes=size,
            storage_key=storage_key,
        )
        db.add(document)
        db.flush()

        _audit(
            db,
            user,
            "document.uploaded",
            "success",
            str(document.id),
            {"size_bytes": size},
        )
        db.commit()
        db.refresh(document)

        return {
            "id": str(document.id),
            "name": document.name,
            "category": document.category,
            "size_bytes": document.size_bytes,
        }

    except HTTPException:
        db.rollback()
        destination.unlink(missing_ok=True)
        raise
    except Exception:
        db.rollback()
        destination.unlink(missing_ok=True)
        raise
    finally:
        await file.close()


@router.get("/{document_id}/download")
def download_document(
    document_id: UUID,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
) -> FileResponse:
    """Return a file only when the user currently has read access."""
    document = db.get(Document, document_id)
    role = (
        effective_document_role(db, user, document)
        if document is not None
        else None
    )

    if document is None or role is None or not can_read(role):
        _audit(db, user, "document.download.denied", "denied", str(document_id))
        db.commit()
        raise HTTPException(status_code=404, detail="Document not found")

    # Storage keys are generated by the server, never accepted from the client.
    if (
        not document.storage_key
        or Path(document.storage_key).name != document.storage_key
    ):
        _audit(db, user, "document.download.denied", "denied", str(document_id))
        db.commit()
        raise HTTPException(status_code=404, detail="Document file not found")

    file_path = (STORAGE_DIR / document.storage_key).resolve()
    if file_path.parent != STORAGE_DIR or not file_path.is_file():
        _audit(db, user, "document.download.denied", "denied", str(document_id))
        db.commit()
        raise HTTPException(status_code=404, detail="Document file not found")

    _audit(db, user, "document.downloaded", "success", str(document_id))
    db.commit()

    return FileResponse(
        path=file_path,
        media_type="application/octet-stream",
        filename=document.name,
        headers={"Cache-Control": "private, no-store"},
    )
